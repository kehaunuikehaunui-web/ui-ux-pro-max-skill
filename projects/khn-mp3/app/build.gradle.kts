// Release signing: keystore.properties (local, git-ignored) or KHN_* env vars (CI).
// Without either, the release APK falls back to the debug key so it still installs.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "KHN_KEYSTORE_PATH")

android {
    namespace = "com.khn.mp3"
    compileSdk = 35

